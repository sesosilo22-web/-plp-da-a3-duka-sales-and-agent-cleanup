import pandas as pd


def clean_agent_data(txns, agents):
    """
    Audit and clean mobile-money agent transactions.

    Parameters
    ----------
    txns : pandas.DataFrame
        Raw transaction records.
    agents : pandas.DataFrame
        Agent register containing agent_id and county.

    Returns
    -------
    tuple
        clean_df: cleaned transaction DataFrame.
        log: DataFrame recording the cleaning actions.
    """

    clean_df = txns.copy()
    log_records = []

    # 1. Remove duplicate transaction IDs
    before = len(clean_df)

    clean_df = clean_df.drop_duplicates(
        subset="txn_id",
        keep="first"
    ).copy()

    removed = before - len(clean_df)

    log_records.append({
        "action": "Removed duplicate transaction IDs",
        "rows_affected": removed
    })

    # 2. Standardise transaction types
    clean_df["txn_type"] = (
        clean_df["txn_type"]
        .astype("string")
        .str.strip()
        .str.lower()
        .map({
            "deposit": "Deposit",
            "withdrawal": "Withdrawal"
        })
    )

    invalid_types = clean_df["txn_type"].isna().sum()

    log_records.append({
        "action": "Standardised transaction types",
        "rows_affected": int(invalid_types)
    })

    # 3. Convert amounts to numeric
    clean_df["amount"] = pd.to_numeric(
        clean_df["amount"],
        errors="coerce"
    )

    missing_before = clean_df["amount"].isna()

    clean_df["amount_imputed"] = missing_before

    # 4. Impute missing amounts using transaction-type medians
    medians = clean_df.groupby("txn_type")["amount"].transform("median")

    clean_df["amount"] = clean_df["amount"].fillna(medians)

    # Fallback if a transaction type has no available median
    overall_median = clean_df["amount"].median()

    clean_df["amount"] = clean_df["amount"].fillna(
        overall_median
    )

    log_records.append({
        "action": "Imputed missing or invalid amounts using transaction-type median",
        "rows_affected": int(missing_before.sum())
    })

    # 5. Convert dates, including slash-formatted dates
    clean_df["txn_date"] = pd.to_datetime(
        clean_df["txn_date"],
        errors="coerce",
        format="mixed"
    )

    invalid_dates = clean_df["txn_date"].isna().sum()

    log_records.append({
        "action": "Converted transaction dates",
        "rows_affected": int(invalid_dates)
    })

    # 6. Detect outliers using the IQR method
    q1 = clean_df["amount"].quantile(0.25)
    q3 = clean_df["amount"].quantile(0.75)

    iqr = q3 - q1

    lower_bound = q1 - 1.5 * iqr
    upper_bound = q3 + 1.5 * iqr

    clean_df["is_outlier"] = (
        (clean_df["amount"] < lower_bound)
        | (clean_df["amount"] > upper_bound)
    )

    log_records.append({
        "action": "Flagged IQR outliers",
        "rows_affected": int(clean_df["is_outlier"].sum())
    })

    # 7. Merge agent information
    clean_df = clean_df.merge(
        agents[["agent_id", "county"]],
        on="agent_id",
        how="left",
        indicator=True,
        validate="many_to_one"
    )

    clean_df["unknown_agent"] = (
        clean_df["_merge"] == "left_only"
    )

    unknown_count = int(clean_df["unknown_agent"].sum())

    clean_df["county"] = clean_df["county"].fillna("Unknown")

    clean_df = clean_df.drop(columns="_merge")

    log_records.append({
        "action": "Identified transactions with unknown agents",
        "rows_affected": unknown_count
    })

    # 8. Return a cleaning log
    log = pd.DataFrame(log_records)

    return clean_df, log